#Write a query to list products where stock quantity < 10 in any store.
SELECT * FROM PRODUCTS;
SELECT * FROM STOCKS;
SELECT * FROM STORES;
SELECT P.Product_Id,P.Product_Name,SO.Quantity,st.Store_Name,st.Store_Id
FROM Products as P JOIN STOCKS AS SO ON SO.Product_Id=p.Product_Id
JOIN stores as st ON st.Store_Id=SO.Store_Id
WHERE SO.Quantity <10;

