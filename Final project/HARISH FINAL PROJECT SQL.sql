#Customer Purchase Summary 
#For each customer, return total orders placed, total items purchased,and total revenue. 
SELECT * FROM ORDERS;
SELECT * FROM ORDER_ITEMS;
SELECT * FROM CUSTOMERS;
SELECT C.CUSTOMER_ID,C.CUSTOMER_NAME,count(distinct(O.ORDER_ID)) AS TotalOrder,sum(OI.QUANTITY)AS TotalItems,
sum(oi.total_price) as TotalRevenue
FROM CUSTOMERS AS C
JOIN ORDERS AS O ON C.CUSTOMER_ID=O.CUSTOMER_ID
JOIN ORDER_ITEMS AS OI ON O.ORDER_ID=OI.ORDER_ID
GROUP BY C.CUSTOMER_ID,C.CUSTOMER_NAME;

#Task 7
#Segment Customers by Total Spend
#Write a query to classify customers into spending brackets (e.g., low, medium, high). 
SELECT C.Customer_Name,C.Customer_Id,
sum(OI.total_price) AS TotalSpend,
case
WHEN(OI.Total_Price)<200 THEN "LOW"
when(OI.Total_Price) BETWEEN 200 AND 300 THEN "MEDIUM"
ELSE "HIGH"
END AS SpendingBrackets
FROM CUSTOMERS AS C JOIN ORDERS AS O ON C.Customer_ID=O.Customer_ID
JOIN ORDER_ITEMS AS OI ON O.Order_Id=OI.Order_Id
GROUP BY C.Customer_Name,C.Customer_Id,Total_Price
ORDER BY TotalSpend asc;	

